import { readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { marked } from './vendor/marked.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const config = JSON.parse(await readFile(path.join(root, 'site.json'), 'utf8'));
const marker = '<!-- Generated by tools/build.mjs; edit Markdown, site.json or the builder. -->';
const escape = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const dateLabel = (date) => new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(`${date}T00:00:00Z`));

function page({ title, description, prefix, content, source }) {
  return `${marker}
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(description)}">
  <title>${escape(title)} | ${escape(config.account)}</title>
  <link rel="stylesheet" href="${prefix}assets/style.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header"><a class="site-name" href="${prefix}index.html">${escape(config.siteName)}</a><span class="account">${escape(config.account)}</span></header>
  <main id="main" tabindex="-1">${content}</main>
  <footer class="site-footer"><a href="${prefix}index.html">All notes</a>${source ? `<a href="${source}">Markdown source</a>` : ''}</footer>
</body>
</html>
`;
}

async function save(relative, html) {
  const target = path.join(root, relative);
  let existing;
  try { existing = await readFile(target, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing !== undefined && !existing.startsWith(marker)) {
    throw new Error(`Refusing to overwrite an unrecognized file: ${relative}`);
  }
  await writeFile(target, html, 'utf8');
  console.log(`Built ${relative}`);
}

const posts = [];
for (const post of config.posts) {
  if (!/^[a-z0-9-]+$/.test(post.slug)) throw new Error('Invalid post slug');
  const md = await readFile(path.join(root, 'posts', `${post.slug}.md`), 'utf8');
  const heading = md.match(/^# (.+)\r?\n/);
  if (!heading) throw new Error(`Missing title: ${post.slug}`);
  const title = heading[1];
  const body = marked.parse(md.slice(heading[0].length), { gfm: true, breaks: false });
  for (const match of body.matchAll(/(?:src|href)="([^"#]+)"/g)) {
    if (/^[a-z]+:/i.test(match[1])) continue;
    const local = path.resolve(root, 'posts', match[1]);
    const relative = path.relative(root, local);
    if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Link outside site');
    await access(local);
  }
  posts.push({ ...post, title });
  await save(`posts/${post.slug}.html`, page({
    title, description: post.excerpt, prefix: '../', source: `${post.slug}.md`,
    content: `<article class="article"><header><time class="meta" datetime="${escape(post.date)}">${dateLabel(post.date)}</time><h1>${escape(title)}</h1></header>\n${body}</article>`
  }));
}

await save('index.html', page({
  title: config.siteName, description: 'Research notes on oblique water entry.', prefix: '',
  content: `<h1>${escape(config.siteName)}</h1><ol class="post-list">${posts.map((post) => `<li><time class="post-date" datetime="${escape(post.date)}">${dateLabel(post.date)}</time><h2><a href="posts/${post.slug}.html">${escape(post.title)}</a></h2><p>${escape(post.excerpt)}</p></li>`).join('\n')}</ol>`
}));
